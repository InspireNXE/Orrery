#define SLOT(vtable, method, name) printf("    public const int %s = %zu;\n", name, offsetof(vtable, method) / sizeof(void *))
#define C(name, value) printf("    public const int %s = %d;\n", name, (int)(value))
#define S(name, value) printf("    public const string %s = \"%ls\";\n", name, value)
#define E(name) printf("    %s = %d,\n", #name, (int)(name))

static void guid(const char *name, AMFGuid g)
{
    struct { unsigned int a; unsigned short b, c; unsigned char d[8]; } raw;
    memcpy(&raw, &g, sizeof raw);
    printf("    public static readonly Guid %s = new(0x%08x, 0x%04x, 0x%04x, 0x%02x, 0x%02x, 0x%02x, 0x%02x, 0x%02x, 0x%02x, 0x%02x, 0x%02x);\n",
           name, raw.a, raw.b, raw.c, raw.d[0], raw.d[1], raw.d[2], raw.d[3], raw.d[4], raw.d[5], raw.d[6], raw.d[7]);
}

