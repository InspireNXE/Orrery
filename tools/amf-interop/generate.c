/*
 * Prints src/Orrery.Host/Encoding/Amf/AmfInterop.g.cs from AMD's AMF headers, compiled as C so the headers' own C
 * vtable structs give every slot number: offsetof(vtable, method) / sizeof(void*). Sizes, IIDs, enum values and
 * property names come from the compiler too. Run through Generate-AmfInterop.ps1, which fetches the pinned headers
 * and checks each one's hash first.
 *
 * Windows x64 only: AMF's property names are wchar_t, which is UTF-16 there and UTF-32 on Linux, where AMF also
 * works through Vulkan rather than D3D11.
 */
#include <stddef.h>
#include <stdio.h>
#include <string.h>
