/* The mask a bitfield occupies in its 32-bit word: set it to all ones in a zeroed struct and read the word back. */
#define MASK(T, word_offset, member, name)                                   \
    do {                                                                     \
        T s;                                                                 \
        unsigned w;                                                          \
        memset(&s, 0, sizeof s);                                             \
        s.member = ~0u;                                                      \
        memcpy(&w, (char *)&s + (word_offset), sizeof w);                    \
        printf("    public const uint %s = 0x%08x;\n", name, w);             \
    } while (0)

