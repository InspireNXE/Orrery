static void name_of(const char *member, char *out)
{
    for (; *member; member++, out++)
        *out = *member == '.' ? '_' : *member;
    *out = 0;
}

static void field(size_t offset, const char *type, const char *member)
{
    char name[256];
    name_of(member, name);
    printf("    [FieldOffset(%zu)] public %s %s;\n", offset, type, name);
}

#define BEGIN(T) printf("\n[StructLayout(LayoutKind.Explicit, Size = %zu)]\nstruct " #T "\n{\n", sizeof(T))
#define END() printf("}\n")
#define F(T, member, type) field(offsetof(T, member), type, #member)

static void guid(const char *name, GUID g)
{
    printf("    public static readonly Guid %s = new(0x%08lx, 0x%04x, 0x%04x, 0x%02x, 0x%02x, 0x%02x, 0x%02x, 0x%02x, 0x%02x, 0x%02x, 0x%02x);\n",
           name, (unsigned long)g.Data1, g.Data2, g.Data3, g.Data4[0], g.Data4[1], g.Data4[2], g.Data4[3], g.Data4[4],
           g.Data4[5], g.Data4[6], g.Data4[7]);
}

